import { formatDate, formatTime, formatKg, formatTons } from './calculations';

/**
 * Creates formatted WhatsApp message for a Weighbridge Entry
 */
export function formatWeighbridgeWhatsAppText(entry, company) {
  const compName = company?.companyName || 'YASH ENTERPRISE';
  return `*${compName.toUpperCase()}*
*WEIGHBRIDGE SLIP*
--------------------------------
*Slip No:* ${entry.slipNumber}
*Date:* ${formatDate(entry.date)} ${formatTime(entry.date)}
--------------------------------
*Party:* ${entry.partyName}
*Vehicle No:* ${entry.vehicleNumber}
*Material:* ${entry.materialName}
*Quantity:* ${entry.quantityBags} Bags (${formatTons(entry.tons)})
--------------------------------
*Gross Weight:* ${formatKg(entry.grossWeightKg)} (${(entry.grossWeightKg / 1000).toFixed(2)} Ton)
*Tare Weight:*  ${formatKg(entry.tareWeightKg)} (${(entry.tareWeightKg / 1000).toFixed(2)} Ton)
*NET WEIGHT:*   ${formatKg(entry.netWeightKg)} (${(entry.netWeightKg / 1000).toFixed(2)} Ton)
--------------------------------
*Remarks:* ${entry.remarks || 'None'}
_Electronic Slip generated by YASH ENTERPRISE Management System_`;
}

/**
 * Creates formatted WhatsApp message for a Delivery Note
 */
export function formatDeliveryNoteWhatsAppText(dn, company) {
  const compName = company?.companyName || 'YASH ENTERPRISE';
  const productsText = (dn.products || []).map((p, idx) => 
    `${idx + 1}. *${p.particular}* - ${p.quantityBags} Bags (${p.bagWeightKg} KG) = ${p.tons} Ton`
  ).join('\n');

  return `*${compName.toUpperCase()}*
*DELIVERY NOTE*
--------------------------------
*DN No:* ${dn.deliveryNoteNumber}
*Date:* ${formatDate(dn.date)}
*Party:* ${dn.partyName}
*Vehicle:* ${dn.vehicleNumber} ${dn.driverPhone ? `(Ph: ${dn.driverPhone})` : ''}
*Delivery Loc:* ${dn.deliveryLocation || 'As per order'}
*Freight:* ${dn.freight || 'Standard'}
--------------------------------
*Items:*
${productsText}
--------------------------------
*Total Bags:* ${dn.totalBags} Bags
*Total Tons:* ${dn.totalTons} Ton (${formatKg(dn.totalWeightKg)})
*Remarks:* ${dn.remarks || 'None'}
_Delivered by YASH ENTERPRISE_`;
}

/**
 * Opens WhatsApp web / mobile with prefilled message
 */
export function shareViaWhatsApp(text, phone = '') {
  const cleanPhone = phone.replace(/[^0-9]/g, '');
  const encoded = encodeURIComponent(text);
  const url = cleanPhone ? `https://wa.me/${cleanPhone}?text=${encoded}` : `https://wa.me/?text=${encoded}`;
  window.open(url, '_blank');
}

/**
 * Triggers native Web Share API or falls back to copying text to clipboard
 */
export async function shareDocument(title, text) {
  if (navigator.share) {
    try {
      await navigator.share({
        title,
        text
      });
      return { success: true, method: 'native' };
    } catch (err) {
      if (err.name !== 'AbortError') {
        await copyToClipboard(text);
        return { success: true, method: 'clipboard' };
      }
      return { success: false, method: 'cancelled' };
    }
  } else {
    await copyToClipboard(text);
    return { success: true, method: 'clipboard' };
  }
}

/**
 * Copies plain text to clipboard
 */
export async function copyToClipboard(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch (err) {
    // Fallback
    const textArea = document.createElement('textarea');
    textArea.value = text;
    document.body.appendChild(textArea);
    textArea.select();
    document.execCommand('copy');
    document.body.removeChild(textArea);
    return true;
  }
}
